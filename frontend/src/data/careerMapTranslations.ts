export function localizeCareerMapText(
  text: string,
  lang: 'en' | 'kn',
  careerName: string,
  localizedCareerName: string
): string {
  if (lang !== 'kn') return text

  if (text.startsWith('Subjects and introductory concepts related to ')) {
    return `${localizedCareerName}ಗೆ ಸಂಬಂಧಿಸಿದ ವಿಷಯಗಳು ಮತ್ತು ಪರಿಚಯಾತ್ಮಕ ಪರಿಕಲ್ಪನೆಗಳು`
  }
  if (text.startsWith('Courses and educational routes related to ')) {
    return `${localizedCareerName}ಗೆ ಸಂಬಂಧಿಸಿದ ಕೋರ್ಸ್‌ಗಳು ಮತ್ತು ಶಿಕ್ಷಣದ ಮಾರ್ಗಗಳು`
  }
  if (text.startsWith('Advanced topics and practical learning in ')) {
    return `${localizedCareerName} ಕ್ಷೇತ್ರದ ಉನ್ನತ ವಿಷಯಗಳು ಮತ್ತು ಪ್ರಾಯೋಗಿಕ ಕಲಿಕೆ`
  }
  if (text.startsWith('Explore courses that can help you become a ')) {
    return `${localizedCareerName} ಆಗಲು ಸಹಾಯ ಮಾಡುವ ಕೋರ್ಸ್‌ಗಳನ್ನು ಅನ್ವೇಷಿಸಿ.`
  }

  const mapped = translations[text]
  return mapped ?? text.replaceAll(careerName, localizedCareerName)
}
